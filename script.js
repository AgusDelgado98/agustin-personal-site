const scatterNodeOrder = ['understand', 'ask', 'structure', 'validate', 'build'];

let currentLanguage = 'es';

function applyLanguage(lang) {
  currentLanguage = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[lang][key]) node.textContent = translations[lang][key];
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((node) => {
    const key = node.dataset.i18nAria;
    if (translations[lang][key]) node.setAttribute('aria-label', translations[lang][key]);
  });
  document.querySelectorAll('[data-i18n-alt]').forEach((node) => {
    const key = node.dataset.i18nAlt;
    if (translations[lang][key]) node.setAttribute('alt', translations[lang][key]);
  });
  document.querySelectorAll('.lang-button').forEach(btn => btn.classList.toggle('is-active', btn.dataset.lang === lang));
  localStorage.setItem('personalSiteLanguage', lang);
}

document.querySelectorAll('.lang-button').forEach(btn => btn.addEventListener('click', () => applyLanguage(btn.dataset.lang)));

// --- Mobile nav ---
const navToggle = document.querySelector('.nav-toggle');
const primaryNav = document.getElementById('primary-nav');
function setNavOpen(isOpen) {
  primaryNav.classList.toggle('is-open', isOpen);
  navToggle.setAttribute('aria-expanded', String(isOpen));
}
navToggle.addEventListener('click', () => {
  const willOpen = !primaryNav.classList.contains('is-open');
  setNavOpen(willOpen);
  if (willOpen) {
    const firstLink = primaryNav.querySelector('a');
    if (firstLink) firstLink.focus();
  }
});
primaryNav.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') {
    setNavOpen(false);
    navToggle.focus();
  }
});
primaryNav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => setNavOpen(false)));
document.addEventListener('click', (event) => {
  if (primaryNav.classList.contains('is-open') && !primaryNav.contains(event.target) && !navToggle.contains(event.target)) {
    setNavOpen(false);
  }
});

