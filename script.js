// --- View router ---
function renderView() {
  const view = HASH_TO_VIEW[window.location.hash] || 'home';
  currentView = view;

  document.querySelectorAll('.view').forEach((section) => {
    section.hidden = section.dataset.view !== view;
  });

  document.querySelectorAll('[data-view-link]').forEach((link) => {
    const isActive = link.dataset.viewLink === view && !link.classList.contains('nav-link-external');
    if (link.classList.contains('nav-link')) {
      link.classList.toggle('is-active', isActive);
      if (isActive) link.setAttribute('aria-current', 'page'); else link.removeAttribute('aria-current');
    }
  });

  if (VIEW_TITLES[view]) document.title = VIEW_TITLES[view];

  if (!isFirstRender) {
    window.scrollTo(0, 0);
    const headingId = view === 'about' ? 'about-heading' : view === 'thinking' ? 'thinking-heading' : 'home-heading';
    const heading = document.getElementById(headingId);
    if (heading) heading.focus();
  }
  isFirstRender = false;
}

document.querySelectorAll('[data-view-link]').forEach((link) => {
  if (link.classList.contains('nav-link-external')) return;
  link.addEventListener('click', () => {
    const view = link.dataset.viewLink;
    if (window.location.hash === VIEW_TO_HASH[view]) {
      renderView();
    }
  });
});
window.addEventListener('hashchange', renderView);

