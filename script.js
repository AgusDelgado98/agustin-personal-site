const prefersReducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

// --- Visual system A: hero quiet data field ---
(function initHeroField() {
  const svg = document.getElementById('hero-field');
  if (!svg || prefersReducedMotion) return;
  const dots = Array.from(svg.querySelectorAll('.field-dot'));
  const linksGroup = document.getElementById('hero-field-links');

  const pointerLinks = [];
  for (let i = 0; i < 4; i++) {
    const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
    line.setAttribute('class', 'field-pointer-link');
    linksGroup.appendChild(line);
    pointerLinks.push(line);
  }

  let rafId = null;
  function handleMove(event) {
    if (rafId) return;
    rafId = requestAnimationFrame(() => {
      rafId = null;
      const pt = svg.createSVGPoint();
      pt.x = event.clientX;
      pt.y = event.clientY;
      const ctm = svg.getScreenCTM();
      if (!ctm) return;
      const local = pt.matrixTransform(ctm.inverse());

      const withDist = dots.map(d => {
        const dx = parseFloat(d.getAttribute('cx')) - local.x;
        const dy = parseFloat(d.getAttribute('cy')) - local.y;
        return { d, dist: Math.hypot(dx, dy) };
      }).sort((a, b) => a.dist - b.dist);

      dots.forEach(d => d.classList.remove('is-active'));
      const near = withDist.filter(w => w.dist < 90).slice(0, 4);
      near.forEach((w, i) => {
        w.d.classList.add('is-active');
        const line = pointerLinks[i];
        line.setAttribute('x1', local.x);
        line.setAttribute('y1', local.y);
        line.setAttribute('x2', w.d.getAttribute('cx'));
        line.setAttribute('y2', w.d.getAttribute('cy'));
        line.classList.add('is-active');
      });
      for (let i = near.length; i < pointerLinks.length; i++) {
        pointerLinks[i].classList.remove('is-active');
      }
    });
  }
  function handleLeave() {
    dots.forEach(d => d.classList.remove('is-active'));
    pointerLinks.forEach(l => l.classList.remove('is-active'));
  }
  svg.addEventListener('pointermove', handleMove);
  svg.addEventListener('pointerleave', handleLeave);
})();

// --- Visual system B: journey thread draw-in ---
(function initJourneyThread() {
  const thread = document.querySelector('.journey-thread');
  if (!thread) return;
  if (prefersReducedMotion) return;
  const len = thread.getTotalLength();
  thread.style.strokeDasharray = String(len);
  thread.style.strokeDashoffset = String(len);
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        thread.style.transition = 'stroke-dashoffset 1.4s ease';
        thread.style.strokeDashoffset = '0';
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.4 });
  observer.observe(thread);
})();

// --- Visual system C: How I Work conceptual scatter ---
(function initScatter() {
  const nodes = Array.from(document.querySelectorAll('.scatter-node'));
  const links = Array.from(document.querySelectorAll('.scatter-link'));
  const panel = document.getElementById('scatter-panel');
  if (!nodes.length || !panel) return;

  function activate(nodeId) {
    nodes.forEach((btn) => {
      const isActive = btn.dataset.node === nodeId;
      btn.classList.toggle('is-active', isActive);
      btn.setAttribute('aria-pressed', String(isActive));
    });
    links.forEach((line) => {
      const pair = line.dataset.pair.split('-');
      line.classList.toggle('is-highlighted', pair.includes(nodeId));
    });
    const capKey = 'scatter' + nodeId.charAt(0).toUpperCase() + nodeId.slice(1) + 'Text';
    panel.dataset.i18n = capKey;
    panel.textContent = translations[currentLanguage][capKey];
  }

  nodes.forEach((btn) => {
    btn.addEventListener('mouseenter', () => activate(btn.dataset.node));
    btn.addEventListener('focus', () => activate(btn.dataset.node));
    btn.addEventListener('click', () => activate(btn.dataset.node));
  });

  activate(scatterNodeOrder[0]);
})();

