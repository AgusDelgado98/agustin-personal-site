(function initThinking() {
  const nodes = Array.from(document.querySelectorAll('.thinking-item'));
  const titleEl = document.getElementById('thinking-panel-title');
  const textEl = document.getElementById('thinking-panel-text');
  if (!nodes.length || !titleEl || !textEl) return;

  function activate(nodeId) {
    nodes.forEach((btn) => {
      const isActive = btn.dataset.node === nodeId;
      btn.classList.toggle('is-active', isActive);
      btn.setAttribute('aria-pressed', String(isActive));
    });
    const titleKey = 'think' + nodeId.charAt(0).toUpperCase() + nodeId.slice(1) + 'Title';
    const textKey = 'think' + nodeId.charAt(0).toUpperCase() + nodeId.slice(1) + 'Text';
    titleEl.dataset.i18n = titleKey;
    textEl.dataset.i18n = textKey;
    titleEl.textContent = translations[currentLanguage][titleKey];
    textEl.textContent = translations[currentLanguage][textKey];
  }

  nodes.forEach((btn) => {
    btn.addEventListener('mouseenter', () => activate(btn.dataset.node));
    btn.addEventListener('focus', () => activate(btn.dataset.node));
    btn.addEventListener('click', () => activate(btn.dataset.node));
  });

  activate(thinkingNodeOrder[0]);
})();

// --- Knowledge map and journey connections ---
document.querySelectorAll('[data-connection-group]').forEach((group) => {
  const buttons = Array.from(group.querySelectorAll('[data-connection]'));
  const edges = Array.from(group.querySelectorAll('[data-connects]')).map(element => ({
    element,
    nodes: element.dataset.connects.split(' ')
  }));
  const description = group.querySelector('.map-readout .body-text');
  const related = group.querySelector('.map-related');

  function activate(button) {
    const id = button.dataset.connection;
    const neighbors = new Set();
    edges.forEach(({ element, nodes }) => {
      const active = nodes.includes(id);
      element.classList.toggle('is-connected', active);
      if (active) nodes.forEach(node => neighbors.add(node));
    });
    buttons.forEach((node) => {
      const selected = node === button;
      node.setAttribute('aria-pressed', String(selected));
      node.classList.toggle('is-related', !selected && neighbors.has(node.dataset.connection));
    });
    if (description) {
      const label = button.dataset.label;
      for (const [element, suffix] of [[description, 'Text'], [related, 'Related']]) {
        const key = label + suffix;
        element.dataset.i18n = key;
        if (element.textContent !== translations[currentLanguage][key]) {
          element.textContent = translations[currentLanguage][key];
        }
      }
    }
  }

  buttons.forEach((button) => {
    const hoverArea = button.closest('.journey-caption') || button;
    hoverArea.addEventListener('pointerenter', (event) => {
      if (event.pointerType === 'mouse') activate(button);
    });
    button.addEventListener('focus', () => activate(button));
    button.addEventListener('click', () => activate(button));
  });
  const initial = buttons.find(button => button.dataset.connection === group.dataset.active);
  if (initial) activate(initial);
});

