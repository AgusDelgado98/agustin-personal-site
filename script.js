(function initHeroField() {
  const svg = document.getElementById('hero-field');
  if (!svg) return;
  const hero = svg.closest('.hero');
  const motion = window.matchMedia('(prefers-reduced-motion: reduce)');
  const dots = Array.from(svg.querySelectorAll('.field-dot'), (element) => ({
    element,
    x: parseFloat(element.getAttribute('cx')) / 100,
    y: parseFloat(element.getAttribute('cy')) / 100
  }));
  const links = svg.querySelector('#hero-field-links');
  const pointerLinks = Array.from({ length: 3 }, () => {
    const line = document.createElementNS('http://www.w3.org/2000/svg', 'line');
    line.setAttribute('class', 'field-pointer-link');
    links.appendChild(line);
    return line;
  });

  let frame;
  let pointer;
  let active = new Set();

  function paint() {
    frame = undefined;
    const { left, top, width, height } = svg.getBoundingClientRect();
    if (!width || !height) return;
    const x = pointer.clientX - left;
    const y = pointer.clientY - top;
    const radius = Math.min(224, Math.max(120, width * .17));
    const nearby = dots.map((dot) => {
      const px = dot.x * width;
      const py = dot.y * height;
      return { element: dot.element, x: px, y: py, distance: Math.hypot(px - x, py - y) };
    }).filter(dot => dot.distance < radius)
      .sort((a, b) => a.distance - b.distance)
      .slice(0, pointerLinks.length);

    const next = new Set(nearby.map(dot => dot.element));
    active.forEach(dot => { if (!next.has(dot)) dot.classList.remove('is-active'); });
    next.forEach(dot => { if (!active.has(dot)) dot.classList.add('is-active'); });
    active = next;

    pointerLinks.forEach((line, index) => {
      const dot = nearby[index];
      if (!dot) {
        line.style.opacity = '0';
        return;
      }
      line.setAttribute('x1', x);
      line.setAttribute('y1', y);
      line.setAttribute('x2', dot.x);
      line.setAttribute('y2', dot.y);
      line.style.opacity = String(.42 * (1 - dot.distance / radius));
    });
  }

  function clear() {
    if (frame !== undefined) cancelAnimationFrame(frame);
    frame = undefined;
    active.forEach(dot => dot.classList.remove('is-active'));
    active.clear();
    pointerLinks.forEach(line => { line.style.opacity = '0'; });
  }

  hero.addEventListener('pointermove', (event) => {
    if (motion.matches || event.pointerType === 'touch') return;
    pointer = event;
    if (frame === undefined) frame = requestAnimationFrame(paint);
  }, { passive: true });
  hero.addEventListener('pointerleave', clear);
  hero.addEventListener('pointercancel', clear);
  motion.addEventListener('change', clear);
})();

// --- Visual system B: journey thread draw-in ---
(function initJourneyThread() {
  const thread = document.querySelector('.journey-thread');
  if (!thread) return;
  if (prefersReducedMotion) return;
  const len = thread.getTotalLength();
  thread.style.strokeDasharray = String(len);
  thread.style.strokeDashoffset = String(len);
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        thread.style.transition = 'stroke-dashoffset 1.4s ease';
        thread.style.strokeDashoffset = '0';
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.4 });
  observer.observe(thread);
})();

